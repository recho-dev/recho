const char = (x) => String.fromCharCode(round(x));

const round = Math.round;

function compactMatrix(callback, n) {
  write(callback, true, n);
}

function write(callback, compact = false, n = 40) {
  for (let i = 0; i < n * 0.4; i++) {
    let output = "";
    while (output.length < n) {
      output += callback();
    }
    print(output, compact);
  }
}

function writeEach(callback, compact = false, n = 40) {
  let output = "";
  let i = 0;

  const timer = setInterval(() => {
    if (i > n * n * 0.25 - 1) return clearInterval(timer);
    echo.clear();
    const j = i % n;
    const v = callback();
    output += v;
    if (j >= n - v.length) output += "\n";
    echo.set("compact", compact)(recho.inspect(output.trim(), {quote: false}));
    i += v.length;
  }, 15);

  echo.dispose(() => clearInterval(timer));
}

function print(text, compact = false) {
  echo.set("compact", compact)(recho.inspect(text, {quote: false}));
}

function rand(n = 1) {
  return (Math.random() - 0.5) * n;
}


