/**
 * ============================================================================
 * =                       Animated Mandelbrot Set                            =
 * ============================================================================
 *
 * The static Mandelbrot set[1] example draws a fractal once. Here the same
 * iteration is driven by `recho.now()`, so the amount of detail breathes over
 * time.
 *
 * `t` is a sine wave in [-1, 1]. Adding 2 shifts it into [1, 3], which a log
 * scale then maps onto iteration counts from 1 to 80. A log scale keeps the
 * early, low-iteration frames from flashing past, so you can watch the set
 * fill in.
 *
 * Feel free to tweak `cols`, `rows`, and `colors` to see the changes!
 */

const now = recho.now();
const t = Math.sin(now / 1000);
const scale = d3.scaleLog([1, 3], [1, 80]);
const cols = 60;
const rows = 20;
const maxIter = ~~scale(t + 2);
const colors = ["@", "%", "#", "*", "+", "=", "~", "-", ":", "."].reverse();

//➜ ................................:::::::-~~=-::::............
//➜ .............................:::::::::-~@@=-::::::..........
//➜ ...........................::::::::---~@@@@*--:::::.........
//➜ .........................:::::::-~=~~~=@@@@+~~---+::........
//➜ .......................:::::::--~*@@@@@@@@@@@@@+*@~::.......
//➜ ....................::::::::---~+@@@@@@@@@@@@@@@@+-::.......
//➜ ................::::-=~-------~+@@@@@@@@@@@@@@@@@*~-::......
//➜ ............::::::::-~+@+*@#~~=@@@@@@@@@@@@@@@@@@@=-::......
//➜ ..........:::::::::--+*@@@@@@%#@@@@@@@@@@@@@@@@@@@@-:::.....
//➜ .........:::::----~***@@@@@@@@@@@@@@@@@@@@@@@@@@@@-::::.....
//➜ .........@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@+~-::::.....
//➜ .........:::::----~***@@@@@@@@@@@@@@@@@@@@@@@@@@@@-::::.....
//➜ ..........:::::::::--+*@@@@@@%#@@@@@@@@@@@@@@@@@@@@-:::.....
//➜ ............::::::::-~+@+*@#~~=@@@@@@@@@@@@@@@@@@@=-::......
//➜ ................::::-=~-------~+@@@@@@@@@@@@@@@@@*~-::......
//➜ ....................::::::::---~+@@@@@@@@@@@@@@@@+-::.......
//➜ .......................:::::::--~*@@@@@@@@@@@@@+*@~::.......
//➜ .........................:::::::-~=~~~=@@@@+~~---+::........
//➜ ...........................::::::::---~@@@@*--:::::.........
//➜ .............................:::::::::-~@@=-::::::..........
{
  let output = "";
  for (let y = 0; y < rows; y++) {
    for (let x = 0; x < cols; x++) {
      const re = map(x, 0, cols, -2.5, 1);
      const im = map(y, 0, rows, -1, 1);
      let [a, b, i] = [0, 0, 0];
      while (i < maxIter) {
        [a, b] = [a * a - b * b + re, 2 * a * b + im];
        if (a * a + b * b > 4) break;
        i++;
      }
      const index = ~~((i / maxIter) * (colors.length - 1));
      output += colors[index];
    }
    output += y === rows - 1 ? "" : "\n";
  }
  echo(output);
}

function map(x, d0, d1, r0, r1) {
  return r0 + ((r1 - r0) * (x - d0)) / (d1 - d0);
}

const d3 = recho.require("d3-scale");

